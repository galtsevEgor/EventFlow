ALTER TYPE "OrderState" ADD VALUE 'REFUNDED';
CREATE TABLE "OrderRefund" (
  id UUID PRIMARY KEY, "orderId" UUID NOT NULL UNIQUE REFERENCES "Order"(id),
  "actorSubject" VARCHAR(255) NOT NULL, reason VARCHAR(240) NOT NULL,
  state VARCHAR(20) NOT NULL DEFAULT 'FENCING' CHECK (state IN ('FENCING','PENDING','REQUIRES_REVIEW','REJECTED','SUCCEEDED')),
  code VARCHAR(60), "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "completedAt" TIMESTAMPTZ(3)
);
CREATE TABLE "RefundRequest" (
  "actorSubject" VARCHAR(255) NOT NULL, key UUID NOT NULL, "payloadHash" CHAR(64) NOT NULL,
  "operationId" UUID NOT NULL REFERENCES "OrderRefund"(id), "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("actorSubject", key)
);
